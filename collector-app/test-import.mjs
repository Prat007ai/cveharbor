import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import '../asset-import.js';
const root=process.argv[2]||'verification';
const read=name=>fs.readFileSync(path.join(fs.readFileSync(path.join(root,name+'-path.txt'),'utf8').trim(),'cveharbor-assets.csv'),'utf8');
const parsed=globalThis.CVEHARBOR_ASSET_IMPORT.parse(read('fixture'));
assert.equal(parsed.entries.length,7);
assert.equal(parsed.duplicates,0);
assert.ok(parsed.entries.every(p=>p.name==='NORTHSTAR-WEB01'&&p.asset_type==='Server'&&p.notes.startsWith('Server role: Web / Application;')));
assert.deepEqual(parsed.entries.filter(p=>p.technology==='.NET Runtime').map(p=>p.version),['8.0.1','8.0.2']);
assert.equal(parsed.warnings.length,1);
assert.equal(parsed.networks.length,1);
assert.deepEqual(parsed.networks[0].snapshot.suggested,{adapter_id:'demo-backup',ip:'198.51.100.47'});
assert.equal(parsed.networks[0].snapshot.adapters.length,3);
assert.equal(parsed.networks[0].snapshot.adapters.flatMap(a=>a.addresses).length,4);
assert.ok(parsed.entries.some(p=>p.technology==='\'=Fictional, "Spreadsheet" App'&&p.version==="'+1.0"));
const large=globalThis.CVEHARBOR_ASSET_IMPORT.parse(read('large-fixture'));
assert.equal(large.entries.length,407);
assert.equal(large.networks[0].snapshot.suggested,null);
assert.ok(large.entries.every(p=>p.notes.startsWith('Server role: Database;')));
console.log('PASS: native app CSV accepted by the actual CVEHarbor parser; hostname, roles, primary choice, all adapters, IPv6, missing version and >128KB single file.');
