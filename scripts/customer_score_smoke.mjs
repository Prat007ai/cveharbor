import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={window:{}};
vm.runInNewContext(fs.readFileSync('customer-score.js','utf8'),context);
const fn=context.window.CVEHARBOR_SCORE.assessCustomer;
const empty=fn({assets:[],issues:[]});
assert.equal(empty.score,null);
assert.equal(empty.confidence,'Low');
const assets=[{id:'a',technology:'WordPress Plugin: Autoptimize',version:'3.1.13'},{id:'b',technology:'PHP',version:'8.3.36'}];
const issues=[{id:'CVE-2026-12345',asset_id:'a',level:'version_review',severity:'high'}];
const checks={a:{status:'checked',installed_version:'3.1.13',release:{update_status:'Update Available'}}};
const assessment=fn({assets,issues,checks,statuses:{}});
assert.ok(Number.isInteger(assessment.score));
assert.ok(assessment.score>=0&&assessment.score<=100);
assert.equal(assessment.confidence,'High');
assert.ok(assessment.parts.currency>0);
assert.equal(fn({assets,issues,checks:{},statuses:{}}).score,null);
assert.equal(fn({assets,issues,checks,statuses:{'a|CVE-2026-12345':'Fixed/Patched'}}).open_candidates,0);
console.log('Customer scoring tests passed');
